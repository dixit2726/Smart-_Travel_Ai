def fmt_currency(val) -> str:
    """Format numeric values as Indian Rupee string using 'Rs.' to ensure clean PDF rendering without black square glyph boxes."""
    try:
        amt = float(val)
        if math.isnan(amt):
            return "Rs. 0"
        if amt == int(amt):
            return f"Rs. {int(amt):,}"
        return f"Rs. {amt:,.2f}"
    except (ValueError, TypeError):
        return "Rs. 0"


def clean_pdf_data(obj):
    """Recursively converts any Unicode Rupee symbol (₹) to 'Rs.' and °C to 'deg C' across all fields."""
    if isinstance(obj, str):
        s = obj.replace("₹", "Rs. ").replace("°C", " deg C").replace("°", " deg ")
        return s
    elif isinstance(obj, dict):
        return {k: clean_pdf_data(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [clean_pdf_data(v) for v in obj]
    return obj


