def register_fonts():
    global FONT_REGULAR, FONT_BOLD
    candidates = [
        ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/segoeuib.ttf"),
        ("C:/Windows/Fonts/arial.ttf", "C:/Windows/Fonts/arialbd.ttf"),
        ("C:/Windows/Fonts/calibri.ttf", "C:/Windows/Fonts/calibrib.ttf"),
        ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
    ]
    for norm_path, bold_path in candidates:
        if os.path.exists(norm_path):
            try:
                pdfmetrics.registerFont(TTFont("SmartFont", norm_path))
                if os.path.exists(bold_path):
                    pdfmetrics.registerFont(TTFont("SmartFont-Bold", bold_path))
                else:
                    pdfmetrics.registerFont(TTFont("SmartFont-Bold", norm_path))
                FONT_REGULAR = "SmartFont"
                FONT_BOLD = "SmartFont-Bold"
                break
            except Exception:
                continue

